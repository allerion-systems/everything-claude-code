#!/usr/bin/env node
/**
 * Allerion Brain — Index
 *
 * Regenerates brain/index.md from the frontmatter of every note.
 * Zero external dependencies.
 *
 * Usage: node scripts/brain-index.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const BRAIN = path.join(ROOT, 'brain');
const NOTES = path.join(BRAIN, 'notes');
const DOMAINS = ['roofing', 'allerion', 'general'];

function parseFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const out = {};
  for (const line of m[1].split('\n')) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let val = line.slice(idx + 1).trim();
    if (val.startsWith('"') && val.endsWith('"')) {
      try {
        val = JSON.parse(val);
      } catch {
        /* keep raw */
      }
    }
    out[key] = val;
  }
  return out;
}

function collectNotes(domain) {
  const dir = path.join(NOTES, domain);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const full = path.join(dir, f);
      const fm = parseFrontmatter(fs.readFileSync(full, 'utf8'));
      return {
        file: path.relative(BRAIN, full),
        title: fm.title || f.replace(/\.md$/, ''),
        status: fm.status || '?',
        tags: fm.tags || '[]',
        source_url: fm.source_url || '',
        ingested: fm.ingested || '',
      };
    })
    .sort((a, b) => (a.ingested < b.ingested ? 1 : -1));
}

function main() {
  const lines = ['# Brain Index', '', '_Generated by `npm run brain:index`. Do not edit by hand._', ''];
  let total = 0;
  for (const domain of DOMAINS) {
    const notes = collectNotes(domain);
    lines.push(`## ${domain} (${notes.length})`, '');
    if (!notes.length) {
      lines.push('_No notes yet._', '');
      continue;
    }
    for (const n of notes) {
      total++;
      const link = `[${n.title}](${n.file})`;
      const src = n.source_url ? ` · [source](${n.source_url})` : '';
      lines.push(`- ${link} — \`${n.status}\` · ${n.ingested} · ${n.tags}${src}`);
    }
    lines.push('');
  }
  lines.push(`_Total notes: ${total}_`, '');
  fs.writeFileSync(path.join(BRAIN, 'index.md'), lines.join('\n'));
  console.log(`Indexed ${total} note(s) -> brain/index.md`);
}

main();
