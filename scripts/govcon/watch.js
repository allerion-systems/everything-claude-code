#!/usr/bin/env node
// Daily SAM.gov opportunity watcher. For each entity profile in entities.json,
// sweeps active notices by keyword, pulls per-notice detail (set-aside, NAICS,
// deadline), filters to what the entity can actually bid, and writes a dated
// markdown digest plus a seen-state file so reruns only surface what's new.
//
// Usage:
//   node scripts/govcon/watch.js            # full run, writes digest + state
//   node scripts/govcon/watch.js --dry      # no state writes
//   node scripts/govcon/watch.js --entity hac   # single entity

const path = require('path');
const fs = require('fs');
const {
  NOTICE_TYPES, samSearch, samDetail, repoRoot, readJson, writeJson,
} = require('./lib');

const DETAIL_BUDGET_PER_ENTITY = 40; // max notice-detail fetches per entity per run
const args = process.argv.slice(2);
const DRY = args.includes('--dry');
const onlyEntity = args.includes('--entity') ? args[args.indexOf('--entity') + 1] : null;

const ROOT = repoRoot();
const STATE_FILE = path.join(ROOT, 'govcon', 'seen.json');
const DIGEST_DIR = path.join(ROOT, 'govcon', 'digests');

function matchesEntity(entity, detail) {
  const hay = `${detail.title} ${detail.description}`.toLowerCase();
  if ((entity.exclude || []).some((x) => hay.includes(x.toLowerCase()))) return false;
  // Set-aside gate: skip notices restricted to programs the entity doesn't hold.
  if (!(entity.setAsideEligible || ['']).includes(detail.setAside)) return false;
  return true;
}

function priority(entity, detail) {
  let score = 0;
  if ((entity.preferSetAsides || []).includes(detail.setAside)) score += 3;
  if ((entity.naics || []).includes(detail.naics)) score += 2;
  // Home-state boost: placeOfPerformance renders as "City, ST"
  if ((entity.popStates || []).some((st) => (detail.placeOfPerformance || '').endsWith(`, ${st}`))) score += 2;
  const hay = `${detail.title} ${detail.description}`.toLowerCase();
  score += (entity.keywords || []).filter((k) => hay.includes(k.toLowerCase())).length;
  return score;
}

async function main() {
  const { entities } = readJson(path.join(__dirname, 'entities.json'), { entities: [] });
  const seen = readJson(STATE_FILE, {});
  const today = new Date().toISOString().slice(0, 10);
  const now = Date.now();
  const report = [];

  for (const entity of entities) {
    if (onlyEntity && entity.id !== onlyEntity) continue;
    const candidates = new Set();
    for (const kw of entity.keywords || []) {
      let results;
      try { results = await samSearch(kw, 15); } catch (err) {
        console.error(`search failed for "${kw}": ${err.message}`);
        continue;
      }
      for (const r of results) {
        const code = (r.type || {}).code;
        if (!NOTICE_TYPES[code]) continue;
        const due = r.responseDate ? Date.parse(r.responseDate) : null;
        if (due && due < now) continue;
        candidates.add(r._id);
      }
    }

    let detailBudget = DETAIL_BUDGET_PER_ENTITY;
    let truncated = 0;
    const rows = [];
    for (const id of candidates) {
      // Notice details are cached globally in seen.json (one notice can match
      // several entities); eligibility is re-checked per entity every run.
      let record = seen[id];
      if (!record || !record.detail) {
        if (detailBudget-- <= 0) { truncated++; continue; }
        let detail;
        try { detail = await samDetail(id); } catch (err) {
          console.error(`detail failed for ${id}: ${err.message}`);
          continue;
        }
        record = seen[id] = { firstSeen: today, entities: {}, detail };
      }
      record.entities = record.entities || {};
      if (!matchesEntity(entity, record.detail)) continue;
      const isNew = !record.entities[entity.id];
      if (isNew && !DRY) record.entities[entity.id] = today;
      rows.push({ ...record.detail, isNew });
    }

    rows.sort((a, b) => priority(entity, b) - priority(entity, a) || (a.responseDeadline || '').localeCompare(b.responseDeadline || ''));
    report.push({ entity, rows, truncated });
  }

  // Render digest
  const lines = [`# GovCon Daily Digest — ${today}`, '',
    '_Auto-generated by scripts/govcon/watch.js from SAM.gov public data. Review before acting; verify set-aside and deadline on the notice itself._', ''];
  for (const { entity, rows, truncated } of report) {
    const fresh = rows.filter((r) => r.isNew);
    lines.push(`## ${entity.name} — ${fresh.length} new / ${rows.length} tracked`);
    lines.push('');
    if (truncated) lines.push(`_Note: ${truncated} candidate notices skipped this run (detail-fetch budget); they will be picked up on the next run._`, '');
    if (!rows.length) { lines.push('_No open matches today._', ''); continue; }
    lines.push('| New | Due | Set-Aside | NAICS | Title | Link |');
    lines.push('|-----|-----|-----------|-------|-------|------|');
    for (const r of rows.slice(0, 25)) {
      const due = (r.responseDeadline || '').slice(0, 10) || 'n/a';
      lines.push(`| ${r.isNew ? '**NEW**' : ''} | ${due} | ${r.setAsideLabel} | ${r.naics || ''} | ${r.title.slice(0, 80).replace(/\|/g, '/')} | [notice](${r.url}) |`);
    }
    lines.push('');
  }
  const digest = lines.join('\n');
  console.log(digest);

  if (!DRY) {
    fs.mkdirSync(DIGEST_DIR, { recursive: true });
    fs.writeFileSync(path.join(DIGEST_DIR, `${today}.md`), digest);
    writeJson(STATE_FILE, seen);
    console.error(`\nwrote govcon/digests/${today}.md and govcon/seen.json`);
  }
}

main().catch((err) => { console.error(err); process.exit(1); });
