#!/usr/bin/env node
/**
 * GovCon watcher — sweeps SAM.gov for open product-supply opportunities per
 * entity profile, dedupes against govcon/seen.json, and writes a digest to
 * govcon/digests/<date>.md (never overwrites an existing digest).
 *
 * Usage: node scripts/govcon/watch.js
 * Requires: Node 18+ (global fetch). No dependencies, no API key.
 *
 * Hard rules (see skills/govcon-pipeline/SKILL.md): this script only reads
 * public data and writes local files. It never submits anything anywhere.
 */

const fs = require('fs');
const path = require('path');
const {
  buildSearchUrl,
  detailUrl,
  isBiddableType,
  withinWindow,
  eligibleSetAside,
  laneForTitle,
  digestRow,
  digestPath,
} = require('./lib');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const GOVCON_DIR = path.join(REPO_ROOT, 'govcon');
const DIGEST_DIR = path.join(GOVCON_DIR, 'digests');
const SEEN_FILE = path.join(GOVCON_DIR, 'seen.json');
const ENTITIES = JSON.parse(fs.readFileSync(path.join(__dirname, 'entities.json'), 'utf8'));

const HEADERS = { Accept: 'application/hal+json', 'User-Agent': 'Mozilla/5.0' };
const DETAIL_FETCH_CAP = 40; // politeness cap per run
const REQUEST_DELAY_MS = 150;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJson(url) {
  const res = await fetch(url, { headers: HEADERS });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

async function sweepEntity(entity, seen, now, windowCfg, detailBudget) {
  const rowsByLane = {};
  const candidates = new Map();

  for (const keywords of Object.values(entity.lanes)) {
    for (const kw of keywords) {
      let data;
      try {
        data = await getJson(buildSearchUrl(kw));
      } catch (err) {
        console.error(`[watch] search failed for "${kw}": ${err.message}`);
        continue;
      }
      await sleep(REQUEST_DELAY_MS);
      for (const r of data?._embedded?.results || []) {
        const typeCode = r.type?.code || '';
        if (!isBiddableType(typeCode, entity.noticeTypes)) continue;
        if (!withinWindow(r.responseDate, now, windowCfg.minDays, windowCfg.maxDays)) continue;
        if (seen[r._id] || candidates.has(r._id)) continue;
        candidates.set(r._id, r);
      }
    }
  }

  for (const [id, r] of candidates) {
    if (detailBudget.used >= DETAIL_FETCH_CAP) break;
    detailBudget.used += 1;
    let setAside = null;
    try {
      const detail = await getJson(detailUrl(id));
      setAside = detail?.data2?.solicitation?.setAside ?? detail?.data?.solicitation?.setAside ?? null;
    } catch (err) {
      console.error(`[watch] detail failed for ${id}: ${err.message}`);
    }
    await sleep(REQUEST_DELAY_MS);
    if (!eligibleSetAside(setAside, entity.eligibleSetAsides)) {
      seen[id] = { skipped: 'set-aside', at: now.toISOString() };
      continue;
    }
    const lane = laneForTitle(r.title, entity.lanes) || 'other';
    (rowsByLane[lane] ||= []).push(
      digestRow({
        id,
        solicitationNumber: r.solicitationNumber,
        title: r.title,
        setAside,
        responseDate: r.responseDate,
      }),
    );
    seen[id] = { sol: r.solicitationNumber, title: (r.title || '').slice(0, 80), at: now.toISOString() };
  }
  return rowsByLane;
}

async function main() {
  const now = new Date();
  const dateStr = now.toISOString().slice(0, 10);
  fs.mkdirSync(DIGEST_DIR, { recursive: true });
  const seen = fs.existsSync(SEEN_FILE) ? JSON.parse(fs.readFileSync(SEEN_FILE, 'utf8')) : {};

  const sections = [`# GovCon digest — ${dateStr}`, ''];
  const detailBudget = { used: 0 };

  for (const entity of ENTITIES.entities) {
    sections.push(`## ${entity.name} (${entity.id})`);
    if (entity.note) sections.push(`> ${entity.note}`);
    if (entity.active === false) {
      sections.push('', '_Entity inactive — skipped._', '');
      continue;
    }
    const rowsByLane = await sweepEntity(entity, seen, now, ENTITIES.window, detailBudget);
    const laneNames = Object.keys(rowsByLane);
    if (laneNames.length === 0) {
      sections.push('', '_No new eligible opportunities this run._', '');
      continue;
    }
    for (const lane of laneNames) {
      sections.push('', `### ${lane}`, '', '| Solicitation | Title | Set-aside | Due | Link |', '|---|---|---|---|---|');
      sections.push(...rowsByLane[lane]);
    }
    sections.push('');
  }

  sections.push('---', 'Generated by scripts/govcon/watch.js from SAM.gov public data. Nothing was submitted anywhere.');

  const outPath = digestPath(DIGEST_DIR, dateStr, fs.existsSync);
  fs.writeFileSync(outPath, sections.join('\n') + '\n');
  fs.writeFileSync(SEEN_FILE, JSON.stringify(seen, null, 1) + '\n');
  console.log(`[watch] digest: ${path.relative(REPO_ROOT, outPath)}`);
  console.log(`[watch] seen entries: ${Object.keys(seen).length}; detail fetches used: ${detailBudget.used}`);
}

main().catch((err) => {
  console.error(`[watch] fatal: ${err.message}`);
  process.exit(1);
});
